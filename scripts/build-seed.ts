// Converts data/roles.csv (curated from aitraining.jobs) into convex/seedData.ts.
// Run: bun scripts/build-seed.ts
import type { Category, SeedRole, Variant } from "../convex/lib/domain";

const BASE = "https://aitraining.jobs";

function parseCsv(text: string): string[][] {
  return text
    .trim()
    .split("\n")
    .slice(1)
    .map((line) => [...line.matchAll(/"([^"]*)"/g)].map((m) => m[1]));
}

function category(raw: string, title: string): Category {
  if (/transcri/i.test(title)) return "transcripcion";
  if (raw === "Transcription & Audio") return "voz";
  if (raw === "Domain Experts") return "expertos";
  if (raw === "Math & STEM" || raw === "Coding") return "tecnico";
  return "evaluacion";
}

const VARIANTS: [RegExp, Variant][] = [
  [/mexic/i, "mx"],
  [/colombia/i, "co"],
  [/argentin|rioplatense/i, "ar"],
  [/chile/i, "cl"],
  [/peru|andean/i, "pe"],
  [/spain|castilian|peninsular/i, "es"],
  [/caribbean|puerto rico/i, "caribe"],
  [/costa ric/i, "cr"],
  [/\(us\)|united states/i, "us"],
  [/latin america|latam/i, "latam"],
];

function variant(title: string): Variant {
  return VARIANTS.find(([re]) => re.test(title))?.[1] ?? "general";
}

const TITLES: [RegExp, string][] = [
  [/voice actor|vo talent|voice cloning/i, "Locución y actuación de voz"],
  [/record/i, "Grabación de voz"],
  [/transcri/i, "Transcripción de audio"],
  [/session director/i, "Dirección de sesiones de audio"],
  [/audiobook/i, "Control de calidad de audiolibros"],
  [/voice|audio/i, "Especialista de audio para IA"],
  [/search engine|internet assessor|ads quality/i, "Evaluación de búsquedas y anuncios"],
  [/tutor/i, "Tutor(a) de IA en español"],
  [/finance|legal|business/i, "Experto(a) en finanzas y negocios"],
  [/science/i, "Experto(a) en ciencias"],
  [/latex/i, "Especialista en LaTeX"],
  [/math/i, "Entrenador(a) de IA en matemáticas"],
  [/coding/i, "Programación para IA"],
  [/team lead|coordinator/i, "Liderazgo de equipo de evaluación"],
  [/evaluat|rater|quality|workspace/i, "Evaluación de respuestas de IA"],
  [/data collection|data contributor/i, "Recolección de datos en español"],
];

function titleEs(title: string): string {
  return TITLES.find(([re]) => re.test(title))?.[1] ?? "Entrenador(a) de IA en español";
}

function pay(raw: string): Pick<SeedRole, "payMin" | "payMax" | "payNote"> {
  const nums = [...raw.matchAll(/\$([\d.]+)/g)].map((m) => Number(m[1]));
  if (nums.length === 0) return {};
  const note = /up to/i.test(raw)
    ? "hasta"
    : /typical/i.test(raw)
      ? "típico"
      : /audio hr/i.test(raw)
        ? "por hora de audio"
        : undefined;
  const payMax = Math.max(...nums);
  const payMin = /up to/i.test(raw) ? undefined : Math.min(...nums);
  return { payMin, payMax, ...(note ? { payNote: note } : {}) };
}

const rows = parseCsv(await Bun.file("data/roles.csv").text());
const roles: SeedRole[] = rows.map(([platform, title, cat, location, posted, payRaw, link], i) => ({
  slug: `r${String(i + 1).padStart(3, "0")}`,
  platform,
  titleEs: titleEs(title),
  titleOriginal: title,
  category: category(cat, title),
  variant: variant(title),
  remote: location === "Remote",
  posted,
  url: BASE + link,
  ...pay(payRaw),
}));

await Bun.write(
  "convex/seedData.ts",
  `// Generated by scripts/build-seed.ts from data/roles.csv. Do not edit by hand.\nimport type { SeedRole } from "./lib/domain";\n\nexport const SEED_ROLES: SeedRole[] = ${JSON.stringify(roles, null, 2)};\n`,
);
console.log(`wrote ${roles.length} roles`);
