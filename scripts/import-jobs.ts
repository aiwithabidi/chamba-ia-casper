// Turns the Apify scrape (.planning/scraped-spanish.json, never committed) into convex/liveRoles.ts.
// Run: bun scripts/import-jobs.ts   Then: bunx convex run roles:seed
import { importJobs, type ScrapedJob } from "../convex/lib/importJobs";

const SOURCE = ".planning/scraped-spanish.json";
const jobs: ScrapedJob[] = await Bun.file(SOURCE).json();
if (!Array.isArray(jobs)) throw new Error(`${SOURCE} is not a JSON array of jobs`);

const { roles, dropped } = importJobs(jobs);
await Bun.write(
  "convex/liveRoles.ts",
  `// Generated by scripts/import-jobs.ts from the wulfcare/ai-training-jobs-scraper Apify actor (MIT). Do not edit by hand.\nimport type { SeedRole } from "./lib/domain";\n\nexport const LIVE_ROLES: SeedRole[] = ${JSON.stringify(roles, null, 2)};\n`,
);
const byCategory = Object.groupBy(roles, (r) => r.category);
console.log(
  JSON.stringify(
    {
      input: jobs.length,
      kept: roles.length,
      dropped,
      byCategory: Object.fromEntries(Object.entries(byCategory).map(([k, v]) => [k, v?.length])),
    },
    null,
    2,
  ),
);
